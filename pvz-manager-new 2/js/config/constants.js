// Реальный звонок при пропуске чекина отправляется НЕ отсюда, а из
// серверной Supabase Edge Function (см. /supabase/functions/check-checkins).
// Она запускается по расписанию (cron) и использует свои ключи
// (ZVONOK_PUBLIC_KEY, ZVONOK_CAMPAIGN_ID), которые хранятся
// в секретах Supabase и никогда не попадают в браузер.
//
// Номер(а) руководителя для звонка хранятся в таблице manager_phones
// в Supabase (управляются через сайт: Дашборд → Настройки), а НЕ здесь —
// чтобы личный номер телефона не был виден всем, кто откроет исходный
// код страницы в открытом репозитории.
//
// Раньше здесь была функция sendZvonokCall(), которая дёргала API zvonok.com
// прямо из браузера — это было небезопасно (API-ключ был виден в исходном
// коде страницы любому посетителю) и не должно использоваться. Не добавляйте
// сюда API-ключи zvonok.com или номера телефонов.

// Функция для расчёта времени дедлайна (за 30 минут до открытия)
export function getDeadlineTime(openTime) {
    const [hours, minutes] = openTime.split(':').map(Number);
    const totalMinutes = hours * 60 + minutes - 30;
    const h = Math.floor(totalMinutes / 60);
    const m = totalMinutes % 60;
    return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}`;
}
